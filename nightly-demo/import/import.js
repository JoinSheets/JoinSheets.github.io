'use strict';

// JoinSheetsImport: parses .xlsx (via vendor/xlsx.full.min.js, SheetJS Community Edition)
// into the host app's lazy columnar source format + a manifest fragment (manifest-<name>.js)
// + a fragment index (manifest.imports.js). All three files are handed to the host app's
// own download mechanism (window.DS_APP.download) -- the user moves them into their data
// directory and refreshes the manifest from the host app's settings screen. Deliberately no
// writing to disk and no adding the source to the current session from here -- see README.md.
//
// Single public entry point: window.DS_APP.importXlsx(file) -- file is already selected by
// the caller (a visible <input type="file">, not a hidden one triggered via .click(): with a
// visible input, cancelling the native dialog simply does nothing, so there is no "hanging"
// promise to account for).
(function (root, factory) {
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = factory({}, {});
  } else {
    root.DS_APP = root.DS_APP || {};
    Object.assign(root.DS_APP, factory(root.DS_APP, root));
  }
})(typeof window !== 'undefined' ? window : this, function (App, root) {

  // ---------------------------------------------------------------------------
  // Pure functions (form serialization/parsing -- no DOM, unit-testable)
  // ---------------------------------------------------------------------------

  // Same contract as the host app's own source format: columns -- one function per field
  // (+ key), returning values for all rows positionally. undefined (not null!) at a row's
  // position means the field was absent for that row; null means explicitly empty/deleted.
  var wrapSourceJs = function (name, payload) {
    var meta = payload.meta;
    var key = meta.key;
    var cols = (key ? [key] : []).concat(meta.labels || []);
    var rows = payload.data || [];
    var cell = function (row, col) {
      return (col in row) ? JSON.stringify(row[col]) : 'undefined';
    };
    var colFns = cols.map(function (col) {
      var values = rows.map(function (row) { return cell(row, col); }).join(', ');
      return '    ' + JSON.stringify(col) + ': function () { return [' + values + ']; }';
    });
    return (
      '// GENERATED by JoinSheetsImport -- do not edit.\n'
      + 'window.DS = window.DS || { sources: {} };\n'
      + 'window.DS.sources[' + JSON.stringify(name) + '] = {\n'
      + '  meta: ' + JSON.stringify(meta, null, 2) + ',\n'
      + '  columns: {\n' + colFns.join(',\n') + '\n  }\n};\n'
    );
  };

  var buildManifestFragmentJs = function (entry) {
    return (
      '// GENERATED by JoinSheetsImport -- manifest fragment for source '
      + JSON.stringify(entry.name) + '.\n'
      + 'window.DS_MANIFEST_FRAGMENT = ' + JSON.stringify({ sources: [entry] }, null, 2) + ';\n'
    );
  };

  var buildImportsIndexJs = function (files) {
    return (
      '// GENERATED by JoinSheetsImport -- index of manifest fragment files.\n'
      + 'window.DS_MANIFEST_IMPORTS = ' + JSON.stringify(files, null, 2) + ';\n'
    );
  };

  // sheet_to_json(sheet, {header:1}) output (array of arrays, first row is the header row)
  // -> { headers, rows }. A short row (fewer cells than headers) leaves the missing fields
  // absent from the row object (see undefined above in wrapSourceJs, not an empty string).
  // Contract: "values are strings" -- every cell is coerced through String().
  var tableFromSheetRows = function (aoa) {
    var headers = (aoa[0] || []).map(function (h) { return String(h); });
    var rows = (aoa.slice(1) || [])
      .filter(function (r) { return r && r.length; })
      .map(function (r) {
        var row = {};
        headers.forEach(function (h, i) {
          if (i < r.length && r[i] !== undefined && r[i] !== '') row[h] = String(r[i]);
        });
        return row;
      });
    return { headers: headers, rows: rows };
  };

  // Extracts DS_MANIFEST_IMPORTS from the text of a file already produced by this same
  // converter -- not arbitrary third-party code, our own format, read the same way a real
  // <script> tag would. A broken/unexpected file just yields an empty list, not an error
  // (the user may have picked the wrong file by mistake -- that should not block the import).
  var parsePriorImportsIndex = function (text) {
    if (!text) return [];
    var sandbox = {};
    try { new Function('window', text)(sandbox); } catch (e) { return []; }
    return sandbox.DS_MANIFEST_IMPORTS || [];
  };

  var mergeImportsIndex = function (prior, newFile) {
    var list = (prior || []).slice();
    if (list.indexOf(newFile) === -1) list.push(newFile);
    return list;
  };

  // ---------------------------------------------------------------------------
  // DOM: dialog (name/key/description/optional prior index) and orchestration
  // ---------------------------------------------------------------------------

  var readArrayBuffer = function (file) {
    return new Promise(function (resolve, reject) {
      var fr = new FileReader();
      fr.onload = function () { resolve(fr.result); };
      fr.onerror = function () { reject(fr.error); };
      fr.readAsArrayBuffer(file);
    });
  };

  var readText = function (file) {
    return new Promise(function (resolve, reject) {
      var fr = new FileReader();
      fr.onload = function () { resolve(fr.result); };
      fr.onerror = function () { reject(fr.error); };
      fr.readAsText(file);
    });
  };

  // A modal dialog -- a plain overlay, with no dependency on the host app's stylesheet
  // (this module should work standalone, regardless of what it's embedded into).
  var showDialog = function (headers) {
    var el = App.el;
    return new Promise(function (resolve, reject) {
      var nameInput = el('input', { type: 'text', style: 'width:100%;box-sizing:border-box' });
      var keySelect = el('select', { style: 'width:100%;box-sizing:border-box' },
        headers.map(function (h) { return el('option', { value: h }, h); }));
      var descInput = el('textarea', { style: 'width:100%;height:4rem;box-sizing:border-box' });
      var priorIndexInput = el('input', { type: 'file', accept: '.js' });
      var cancel = function () { document.body.removeChild(overlay); reject(new Error('cancelled')); };
      var overlay = el('div', {
        style: 'position:fixed;inset:0;background:rgba(0,0,0,.4);display:flex;'
          + 'align-items:center;justify-content:center;z-index:9999;font:14px sans-serif'
      },
        el('div', { style: 'background:#fff;padding:1.5rem;border-radius:6px;max-width:28rem;width:90%' },
          el('h2', { style: 'margin:0 0 .8rem' }, 'Import from Excel'),
          el('label', { style: 'display:block;margin:.5rem 0' }, 'Source name', nameInput),
          el('label', { style: 'display:block;margin:.5rem 0' }, 'Key column', keySelect),
          el('label', { style: 'display:block;margin:.5rem 0' },
            'Description (optional)', descInput),
          el('label', { style: 'display:block;margin:.5rem 0' },
            'Current manifest.imports.js, if any (optional -- so previously added sources '
            + 'aren\'t lost)', priorIndexInput),
          el('div', { style: 'text-align:right;margin-top:1rem' },
            el('button', { type: 'button', onclick: cancel }, 'Cancel'),
            el('button', {
              type: 'button', style: 'margin-left:.5rem',
              onclick: function () {
                var name = (nameInput.value || '').trim();
                if (!name) { alert('Please enter a source name'); return; }
                document.body.removeChild(overlay);
                resolve({
                  name: name,
                  key: keySelect.value,
                  description: (descInput.value || '').trim() || null,
                  priorIndexFile: priorIndexInput.files[0] || null
                });
              }
            }, 'Import')
          )
        )
      );
      document.body.appendChild(overlay);
    });
  };

  // file -- a File already chosen by the user (from a visible <input type="file">, see the
  // comment at the top of this file). Returns Promise<void>; treats a cancelled dialog as not
  // an error for the caller.
  var importXlsx = function (file) {
    if (!file) return Promise.resolve();
    return readArrayBuffer(file).then(function (buf) {
      var wb = root.XLSX.read(buf, { type: 'array' });
      var sheet = wb.Sheets[wb.SheetNames[0]];
      var aoa = root.XLSX.utils.sheet_to_json(sheet, { header: 1 });
      var table = tableFromSheetRows(aoa);
      if (!table.headers.length) { alert('Empty sheet -- no headers in the first row'); return; }

      return showDialog(table.headers).then(function (opts) {
        var priorP = opts.priorIndexFile ? readText(opts.priorIndexFile) : Promise.resolve(null);
        return priorP.then(function (priorText) {
          var labels = table.headers.filter(function (h) { return h !== opts.key; });
          var now = Math.floor(Date.now() / 1000);
          var payload = {
            meta: {
              name: opts.name, key: opts.key, as_of: now, generated_at: now,
              gen_max_cnt: 0, include_archive: false, rows: table.rows.length, labels: labels
            },
            data: table.rows
          };
          var entry = {
            name: opts.name, file: opts.name + '.js', key: opts.key,
            description: opts.description, as_of: now, generated_at: now,
            gen_max_cnt: 0, db_max_cnt: 0, rows: table.rows.length, labels: labels,
            label_types: labels.reduce(function (acc, l) { acc[l] = 'text'; return acc; }, {})
          };
          var fragmentFile = 'manifest-' + opts.name + '.js';
          var index = mergeImportsIndex(parsePriorImportsIndex(priorText), fragmentFile);

          App.download(opts.name + '.js', wrapSourceJs(opts.name, payload), 'text/javascript');
          App.download(fragmentFile, buildManifestFragmentJs(entry), 'text/javascript');
          App.download('manifest.imports.js', buildImportsIndexJs(index), 'text/javascript');
        });
      });
    }).catch(function (e) {
      if (e && e.message !== 'cancelled') { console.error(e); alert('Import failed: ' + e.message); }
    });
  };

  return {
    wrapSourceJs: wrapSourceJs,
    buildManifestFragmentJs: buildManifestFragmentJs,
    buildImportsIndexJs: buildImportsIndexJs,
    tableFromSheetRows: tableFromSheetRows,
    parsePriorImportsIndex: parsePriorImportsIndex,
    mergeImportsIndex: mergeImportsIndex,
    importXlsx: importXlsx
  };
});
